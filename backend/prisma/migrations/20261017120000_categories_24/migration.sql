-- 물건 종류 24개 (#27). 옛 값은 가장 가까운 새 값으로 옮긴다:
-- CARD → ID_CARD, PENCIL_CASE → STATIONERY, LAPTOP_TABLET → LAPTOP, CLOTHING_BAG → BAG. 나머지 6개는 이름 그대로.
ALTER TYPE "Category" RENAME TO "Category_old";
CREATE TYPE "Category" AS ENUM ('WALLET', 'ID_CARD', 'DRIVER_LICENSE', 'PAYMENT_CARD', 'TRANSIT_CARD', 'OTHER_CARD', 'PHONE', 'EARPHONE', 'SMARTWATCH', 'TABLET', 'LAPTOP', 'CHARGER', 'BAG', 'CLOTHING', 'HAT', 'BOOK', 'GLASSES', 'ACCESSORY', 'CASH', 'UMBRELLA', 'TUMBLER', 'KEY', 'STATIONERY', 'ETC');

ALTER TABLE "found_item"
  ALTER COLUMN "category" TYPE "Category" USING (CASE "category"::text WHEN 'CARD' THEN 'ID_CARD' WHEN 'PENCIL_CASE' THEN 'STATIONERY' WHEN 'LAPTOP_TABLET' THEN 'LAPTOP' WHEN 'CLOTHING_BAG' THEN 'BAG' ELSE "category"::text END)::"Category",
  ALTER COLUMN "category_alt" TYPE "Category" USING (CASE "category_alt"::text WHEN 'CARD' THEN 'ID_CARD' WHEN 'PENCIL_CASE' THEN 'STATIONERY' WHEN 'LAPTOP_TABLET' THEN 'LAPTOP' WHEN 'CLOTHING_BAG' THEN 'BAG' ELSE "category_alt"::text END)::"Category";

ALTER TABLE "lost_report"
  ALTER COLUMN "category" TYPE "Category" USING (CASE "category"::text WHEN 'CARD' THEN 'ID_CARD' WHEN 'PENCIL_CASE' THEN 'STATIONERY' WHEN 'LAPTOP_TABLET' THEN 'LAPTOP' WHEN 'CLOTHING_BAG' THEN 'BAG' ELSE "category"::text END)::"Category";

DROP TYPE "Category_old";
